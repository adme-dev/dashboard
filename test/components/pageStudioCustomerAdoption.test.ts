// @vitest-environment happy-dom
import { reactive } from 'vue'
import { afterEach, beforeEach, expect, it, vi } from 'vitest'
import Adoption from '~~/app/components/studio/CustomerAdoption.client.vue'
import { cleanup, click, deferred, flush, mount, otherSite, siteId } from './pageStudioTransferTestSupport'

const fetch = vi.fn()
const props = () => reactive({ grantId: siteId, revision: 1 })
const reference = { grantId: siteId, revision: 1 }
const adoption = { phase: 'idle', adoptionId: null, progress: null, recoveryId: null, recoveryRequired: false, progressDigest: 'a'.repeat(64) }
const status = (resumeRequired = true, value: unknown = null) => ({ grant: reference, result: { resumeRequired, adoption: value } })
const children = { UCard: { template: '<section><slot/></section>' }, UIcon: { template: '<span/>' } }
beforeEach(() => { vi.resetAllMocks(); vi.stubGlobal('$fetch', fetch); fetch.mockResolvedValue(status()) })
afterEach(() => { cleanup(); vi.unstubAllGlobals() })

it('loads only explicit grant status and requires confirmation before connecting a sign-in', async () => {
  const host = await mount(Adoption, props(), children)
  expect(fetch).toHaveBeenCalledExactlyOnceWith(`/api/portal/page-studio/customer/cms-adoption/${siteId}`, { query: { revision: 1 }, retry: 0, timeout: 120000 })
  await click(host, 'Connect this sign-in')
  expect(fetch).toHaveBeenCalledOnce()
  await click(host, 'Cancel')
  expect(fetch).toHaveBeenCalledOnce()
  await click(host, 'Connect this sign-in')
  fetch.mockResolvedValueOnce({ grant: reference, result: { resumed: true } }).mockResolvedValueOnce(status(false, adoption))
  await click(host, 'Continue this step')
  expect(fetch.mock.calls[1][1]).toMatchObject({ method: 'POST', retry: 0, body: { operation: 'resume', grant: reference } })
  expect(fetch).toHaveBeenCalledTimes(3)
  expect(fetch.mock.calls.filter(([, opt]) => opt?.method === 'POST')).toHaveLength(1)
  expect(host.textContent).toContain('Prepare my content')
})
it('advances exactly one saved step and never automatically starts another', async () => {
  fetch.mockResolvedValue(status(false, { ...adoption, phase: 'importing', adoptionId: 'saved-adoption' }))
  const host = await mount(Adoption, props(), children)
  await click(host, 'Continue content setup')
  fetch.mockResolvedValueOnce({ grant: reference, result: { ...adoption, phase: 'ready', adoptionId: 'saved-adoption', progressDigest: 'b'.repeat(64) } })
  await click(host, 'Continue this step')
  expect(fetch.mock.calls[1][1].body).toEqual({ operation: 'adoption', grant: reference, request: { action: 'advance', adoptionId: 'saved-adoption', expectedProgressDigest: 'a'.repeat(64) } })
  expect(fetch).toHaveBeenCalledTimes(2)
})
it('recovery uses the retained expected recovery and one new explicit key', async () => {
  fetch.mockResolvedValue(status(false, { ...adoption, phase: 'importing', adoptionId: 'saved-adoption', recoveryRequired: true, recoveryId: 'prior-recovery' }))
  const host = await mount(Adoption, props(), children)
  await click(host, 'Recover saved setup')
  fetch.mockImplementationOnce(async (_url, options) => ({ grant: reference, result: { ...adoption, phase: 'importing', adoptionId: 'saved-adoption', recoveryId: options.body.request.recoveryId } }))
  await click(host, 'Continue this step')
  expect(fetch.mock.calls[1][1].body.request).toMatchObject({ action: 'recover', adoptionId: 'saved-adoption', expectedRecoveryId: 'prior-recovery', recoveryId: expect.stringMatching(/^[a-f0-9-]{36}$/) })
  expect(fetch).toHaveBeenCalledTimes(2)
})
it('uncertain mutation clears actions, redacts details and requires an explicit read', async () => {
  const host = await mount(Adoption, props(), children)
  await click(host, 'Connect this sign-in')
  fetch.mockRejectedValueOnce(Error('private'))
  await click(host, 'Continue this step')
  expect(host.textContent).toContain('Check your setup access')
  expect(host.textContent).not.toContain('private')
  expect(host.textContent).not.toContain('Connect this sign-in')
  expect(fetch).toHaveBeenCalledTimes(2)
  fetch.mockResolvedValueOnce(status())
  await click(host, 'Refresh setup')
  expect(fetch.mock.calls[2][1].method).toBeUndefined()
  expect(host.textContent).toContain('Connect this sign-in')
})
it.each(['grantId', 'revision'])('rejects mismatched %s in response', async key => {
  fetch.mockResolvedValue({ ...status(), grant: { ...reference, [key]: key === 'revision' ? 2 : otherSite } })
  const host = await mount(Adoption, props(), children)
  expect(host.textContent).toContain('Check your setup access')
  expect(host.textContent).not.toContain('Connect this sign-in')
})
it.each(['grantId', 'revision'])('discards a late response after %s changes', async key => {
  const pending = deferred(), values = props()
  fetch.mockReturnValueOnce(pending.promise).mockRejectedValue({ statusCode: 403 })
  const host = await mount(Adoption, values, children)
  Object.assign(values, { [key]: key === 'revision' ? 2 : otherSite }); await flush()
  pending.resolve(status()); await flush()
  expect(host.textContent).toContain('Check your setup access')
  expect(host.textContent).not.toContain('Connect this sign-in')
})
it('invalid reference makes no request and complete adoption offers no mutation', async () => {
  const invalid = await mount(Adoption, { grantId: siteId, revision: 0 }, children)
  expect(invalid.textContent).toContain('This setup link is incomplete')
  expect(fetch).not.toHaveBeenCalled()
  fetch.mockResolvedValue(status(false, { ...adoption, phase: 'managed', adoptionId: 'saved-adoption' }))
  const complete = await mount(Adoption, props(), children)
  expect(complete.textContent).toContain('Your content is connected')
  expect(complete.textContent).not.toContain('Continue content setup')
  expect(fetch.mock.calls.some(([, opt]) => opt?.method === 'POST')).toBe(false)
})
it('rejects an acknowledgement for another adoption', async () => {
  fetch.mockResolvedValue(status(false, { ...adoption, phase: 'importing', adoptionId: 'saved-adoption' }))
  const host = await mount(Adoption, props(), children)
  await click(host, 'Continue content setup')
  fetch.mockResolvedValueOnce({ grant: reference, result: { ...adoption, phase: 'managed', adoptionId: 'another-adoption' } })
  await click(host, 'Continue this step')
  expect(host.textContent).toContain('Check your setup access')
  expect(host.textContent).not.toContain('Your content is connected')
})

it.each(['blur', 'pageshow'])('discards a delayed read after native sign-in context may change (%s)', async event => {
  const pending = deferred()
  fetch.mockReturnValueOnce(pending.promise)
  const host = await mount(Adoption, props(), children)
  const lifecycle = new Event(event)
  if (event === 'pageshow') Object.defineProperty(lifecycle, 'persisted', { value: true })
  window.dispatchEvent(lifecycle); await flush()
  pending.resolve(status()); await flush()
  expect(host.textContent).not.toContain('Connect this sign-in')
  expect(fetch).toHaveBeenCalledOnce()
  await click(host, 'Refresh setup')
  expect(fetch).toHaveBeenCalledTimes(2)
  expect(host.textContent).toContain('Connect this sign-in')
})
it('discards a delayed mutation after leaving the tab without replaying it', async () => {
  const host = await mount(Adoption, props(), children)
  await click(host, 'Connect this sign-in')
  const pending = deferred()
  fetch.mockReturnValueOnce(pending.promise)
  await click(host, 'Continue this step')
  window.dispatchEvent(new Event('blur')); await flush()
  pending.resolve({ grant: reference, result: { resumed: true } }); await flush()
  expect(host.textContent).not.toContain('Connect this sign-in')
  expect(fetch).toHaveBeenCalledTimes(2)
  window.dispatchEvent(new Event('focus')); await flush()
  expect(fetch).toHaveBeenCalledTimes(2)
})
