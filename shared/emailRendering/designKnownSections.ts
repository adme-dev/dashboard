// Known generated sections that can become structured layers. A section is
// recognised only when re-running its generator with the parsed values
// reproduces the stored HTML byte for byte: the data-edm-layout marker alone is
// never authority. Generator-parameter text (title/copy/button label) is
// carried as authored; any other edit makes the section unknown (left untouched).
import { oemSplit } from '../../app/utils/edmOemLayouts'

export type KnownSplitSection = {
  kind: 'split-photo' | 'split-reverse'
  title: string
  copy: string
  action: string
  path: string
  image: string
  alt: string
  bg: string
  ink: string
  accent: string
  buttonInk: string
}

type Block = { type: string, data: { props?: Record<string, unknown> | null, style?: Record<string, unknown> | null, mobile?: unknown, [key: string]: unknown } }

/** True when a string reads identically as literal text (Heading/Button escape
 * it; native FigFlow shows it as text) and as HTML (the Text layer emits rich
 * HTML). Angle brackets and anything an HTML parser could read as a character
 * reference (`&name`, `&#…`, with or without `;`) are not: such sections are
 * left as their original Html instead of changing their meaning. */
export const literalTextSafe = (value: string) => !/[<>]|&[#a-z0-9]/i.test(value)

/** Conversion boundary for carried links (A0). Structured Image/Button output
 * does not yet have one agreed URL serialization contract, so any `&` in the
 * carried image URL or button path makes the section ineligible: it stays as
 * its original Html, byte for byte. This is deliberately conservative (it also
 * defers ordinary multi-parameter links) and models no HTML parser or names. */
const conversionSafeLink = (value: string) => !value.includes('&')

const unescape = (value: string) => value.replace(/&quot;/g, '"').replace(/&#39;/g, '\'').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&')

/** Parses a split call-to-action generated by `oemSplit`; null unless exact. */
export function parseKnownSplitSection(contents: string): KnownSplitSection | null {
  if (typeof contents !== 'string' || contents.length > 16384) return null
  const kind = /data-edm-layout="(split-photo|split-reverse)"/.exec(contents)?.[1] as KnownSplitSection['kind'] | undefined
  const bg = /table-layout:fixed;background:([^;"<>]+);font-family:/.exec(contents)?.[1]
  const image = /<img src="([^"]*)" alt="([^"]*)" width="276"/.exec(contents)
  const heading = /<h2 class="xf-oem-title" style="[^"]*;color:([^;"]+);">([^<]*)<\/h2>/.exec(contents)
  const copy = /<\/h2><p style="[^"]*;color:([^;"]+);">([^<]*)<\/p>/.exec(contents)
  const action = /<td bgcolor="([^"]+)" style="border-radius:3px;background:[^;"]+;"><a href="https:\/\/example\.com\/([^"]*)" style="[^"]*;color:([^;"]+);">([^<]*)<\/a>/.exec(contents)
  if (!kind || !bg || !image || !heading || !copy || !action) return null
  const parsed: KnownSplitSection = {
    kind, bg, image: unescape(image[1]), alt: unescape(image[2]), ink: heading[1], title: unescape(heading[2]),
    copy: unescape(copy[2]), accent: action[1], path: unescape(action[2]), buttonInk: action[3], action: unescape(action[4])
  }
  if (copy[1] !== parsed.ink) return null
  if (![parsed.title, parsed.copy, parsed.action].every(literalTextSafe) || ![parsed.image, parsed.path].every(conversionSafeLink)) return null
  const regenerated = oemSplit({ title: parsed.title, copy: parsed.copy, action: parsed.action, path: parsed.path, image: parsed.image, alt: parsed.alt, reverse: kind === 'split-reverse', bg: parsed.bg, ink: parsed.ink, accent: parsed.accent, buttonInk: parsed.buttonInk })
  return regenerated.data.props?.contents === contents ? parsed : null
}

/** An unmodified generated Html block: exact generator bytes and no other data. */
export function recogniseKnownSection(block: Block | undefined): KnownSplitSection | null {
  if (!block || block.type !== 'Html') return null
  const props = block.data.props ?? {}
  if (Object.keys(props).some(key => key !== 'contents')) return null
  if (Object.keys(block.data).some(key => !['props', 'style'].includes(key))) return null
  const padding = (block.data.style as { padding?: Record<string, unknown> } | null | undefined)?.padding
  const style = block.data.style ?? {}
  if (Object.keys(style).some(key => key !== 'padding') || (padding && ['top', 'right', 'bottom', 'left'].some(side => padding[side] !== 0))) return null
  return parseKnownSplitSection(String(props.contents ?? ''))
}

/** The structured equivalent: Columns(Image | Heading, Text, Button). Values come
 * only from the recognised persisted section. */
export function knownSplitStructure(section: KnownSplitSection) {
  const side = (top: number, bottom: number, horizontal: number) => ({ top, right: horizontal, bottom, left: horizontal })
  const words: Block[] = [
    { type: 'Heading', data: { props: { text: section.title, level: 'h2' }, style: { backgroundColor: section.bg, color: section.ink, fontFamily: 'MODERN_SANS', fontSize: 32, fontWeight: '700', lineHeight: 1.08, letterSpacing: -1, textAlign: 'left', padding: side(32, 18, 28) }, mobile: { style: { padding: side(28, 16, 22) } } } },
    { type: 'Text', data: { props: { text: section.copy }, style: { backgroundColor: section.bg, color: section.ink, fontFamily: 'MODERN_SANS', fontSize: 16, fontWeight: 'normal', lineHeight: 1.55, textAlign: 'left', padding: side(0, 24, 28) }, mobile: { style: { padding: side(0, 22, 22) } } } },
    { type: 'Button', data: { props: { text: section.action, url: `https://example.com/${section.path}`, buttonBackgroundColor: section.accent, buttonTextColor: section.buttonInk, buttonStyle: 'rectangle', size: 'large' }, style: { backgroundColor: section.bg, fontFamily: 'MODERN_SANS', fontSize: 15, fontWeight: '700', textAlign: 'left', borderRadius: 3, padding: side(0, 32, 28) }, mobile: { style: { padding: side(0, 28, 22) } } } }
  ]
  const photo: Block[] = [{ type: 'Image', data: { props: { url: section.image, alt: section.alt, width: 276 }, style: { padding: side(0, 0, 0), backgroundColor: section.bg } } }]
  const reverse = section.kind === 'split-reverse'
  return {
    container: { type: 'ColumnsContainer', data: { props: { columnsGap: 0, fixedWidths: reverse ? [324, 276] : [276, 324], contentAlignment: 'middle' }, style: { padding: side(0, 0, 0), backgroundColor: section.bg } } } as Block,
    columns: reverse ? [words, photo] : [photo, words]
  }
}
